export const FOODS: Food[] = ROWS.map(
  ([name, calories, protein_g, carbs_g, fat_g, fiber_g, sugar_g, sodium_mg]) => ({
    name, calories, protein_g, carbs_g, fat_g, fiber_g, sugar_g, sodium_mg,
  }),
);

const normalize = (s: string) =>
  s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");

const INDEX = FOODS.map((f) => ({ food: f, key: normalize(f.name) }));

/** Prefix matches first (on any word), then substring matches. */
export function searchFoods(query: string, limit = 8): Food[] {
  const q = normalize(query.trim());
  if (!q) return [];
  const prefix: Food[] = [];
  const contains: Food[] = [];
  for (const { food, key } of INDEX) {
    if (key.startsWith(q) || key.split(/[\s,(&]+/).some((w) => w.startsWith(q))) prefix.push(food);
    else if (key.includes(q)) contains.push(food);
  }
  return [...prefix, ...contains].slice(0, limit);
}
